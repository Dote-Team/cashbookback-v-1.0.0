	public const string Description = """
واجهة برمجة نظام الحسابات: منشآت، وخزائن، وقيود بالدينار والدولار، وصلاحيات بالتوارث، ودخول بالبصمة.

## البدء
1. افتح **POST /API/User/login** ← Try it out، وأرسل اسم المستخدم وكلمة المرور.
2. انسخ `accessToken` من النتيجة.
3. اضغط زر **Authorize** أعلى الصفحة والصق الرمز (دون كلمة Bearer)، ثم Authorize.
4. الآن تعمل كل المسارات باسمك. الرمز صالح 60 دقيقة، وبعدها جدّده عبر **POST /API/User/refresh-token**.

## الخروج التلقائي لعدم النشاط
إن لم يصل أي طلب من الجلسة خلال **5 دقائق** تنتهي، ويعيد أي مسار بعدها 401 مع الترويسة `X-Session-Expired: idle`، ويُرفض تجديد الرمز أيضاً.
الواجهة ترسل **POST /API/User/activity** عند تحريك الفأرة أو الكتابة (مرة كل دقيقة على الأكثر) ليبقى المستخدم داخلاً ما دام يعمل.
المدة في الإعداد `Session__IdleTimeoutMinutes` (0 = معطّل)، وتصل للواجهة في `idleTimeoutMinutes` بنتيجة الدخول.

## شكل الاستجابة
كل المسارات تعيد البنية نفسها:

    { "statusCode": 200, "isSuccess": true, "errorMessages": [], "result": { ... } }

- عند النجاح: البيانات في `result`.
- عند الخطأ: `isSuccess = false` والسبب بالعربية في `errorMessages`، مع رمز HTTP مناسب.
- القوائم المقسّمة صفحات: `result = { data, totalRecords, skip, take }`، و `skip` هو رقم الصفحة ويبدأ من 1.

## المستويات والصلاحيات
| المستوى | من هو | ماذا يستطيع |
|---|---|---|
| 1 سوبر أدمن | موجود في قاعدة البيانات من الإعدادات | كل شيء: المنشآت والخزائن، وإنشاء الأدمن |
| 2 أدمن | ينشئه السوبر أدمن على خزائن معينة | ينشئ مستخدمين بصلاحيات من صلاحياته فقط |
| 3 مستخدم | ينشئه الأدمن | يعمل بصلاحياته، ولا ينشئ أحداً |

الصلاحيات تُمنح **لكل خزنة على حدة**، والقائمة الكاملة من **GET /API/Permission/catalog**.
كل مسار يذكر في شرحه الصلاحية التي يحتاجها.

## لا حذف في النظام
مسارات DELETE **تؤرشف** السجل دون رجعة: يختفي من القوائم والأرصدة، ويبقى في **GET /API/Archive**.
يمكن إرسال سبب الأرشفة في `?reason=`.

## المرفقات
روابط المرفقات في بيانات القيد موقّعة وصالحة 12 ساعة. اعرضها هكذا: `/API/Files/{files}`.
الرفع: صور JPG/PNG/GIF/WEBP أو PDF، حتى 10MB للملف و 5 ملفات للقيد.

## الدخول بالبصمة
البصمة تُلتقط من البرنامج الوسيط على جهاز المستخدم (`http://127.0.0.1:52181/capture`)، ثم تُرسل إلى **POST /API/User/login/fingerprint**.

**تسجيل البصمات للسوبر أدمن فقط:** المستخدم يحضر عنده، فيسجّل له بصمته عبر **POST /API/Fingerprint/enroll** مع `userId`.

## رموز الأخطاء
| الرمز | المعنى |
|---|---|
| 400 | بيانات ناقصة أو غير صالحة |
| 401 | لم تسجّل الدخول، أو الرمز منتهٍ |
| 403 | لا تملك الصلاحية |
| 404 | غير موجود، أو مؤرشف |
| 409 | تعارض، مثل اسم مستخدم مكرر |
| 410 | مسار متوقف نهائياً |
| 413 | حجم الطلب أكبر من المسموح |
| 429 | طلبات كثيرة، انتظر دقيقة |
